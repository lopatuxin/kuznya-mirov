const SAFE_NAME = /^[a-zA-Z0-9_-]+$/;

/**
 * Имя папки игры идёт прямо в путь `/games/<name>/...` — и при заходе по прямой ссылке
 * (`gameSelection.ts`), и при чтении списка игр на экране выбора (`gamesIndex.ts`). Без этой
 * проверки в нём можно было бы пронести выход за пределы папки игр (`../`). Правило одно на оба
 * места: иначе игра, прошедшая в список на экране выбора, могла бы отказать при переходе по своей
 * же ссылке — без единого слова о причине.
 */
export function isValidGameName(name: string): boolean {
  return SAFE_NAME.test(name);
}
